#include "libftprintf.h"

int	ft_putnbr(int nb)
{
	char	c;
	long	n;
	int		count;

	count = 0;
	n = nb;
	if (n < 0)
	{
		count += ft_putchar('-');
		n *= -1;
	}
	if (n >= 10)
		count += ft_putnbr(n / 10);
	c = n % 10 + '0';
	count += ft_putchar(c);
	return (count);
}
